/**
 * Bakes the dotted world map into a compact bitmask.
 *
 * Runs at development time only: it samples real Natural Earth land polygons
 * (via world-atlas) on an equirectangular grid and writes the result as packed
 * base64. The landing page then draws the map from that string, so no map data
 * or geo library ships to the browser.
 *
 *   node scripts/generate-world-dots.mjs
 */
import { writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { geoContains } from 'd3-geo'
import { feature } from 'topojson-client'

const require = createRequire(import.meta.url)
const topology = require('world-atlas/land-110m.json')
const land = feature(topology, topology.objects.land)

/**
 * The panel is 119.5 x 51.23, so the grid keeps that aspect and the dots stay
 * square. Equirectangular maps longitude and latitude linearly, which means
 * the latitude span is fixed by the aspect: 360 / (119.5 / 51.23).
 */
const WIDTH = 150
const HEIGHT = 64
const LAT_MAX = 84
const LAT_MIN = LAT_MAX - 360 / (WIDTH / HEIGHT)

const bits = []
for (let y = 0; y < HEIGHT; y += 1) {
    for (let x = 0; x < WIDTH; x += 1) {
        const lon = -180 + ((x + 0.5) / WIDTH) * 360
        const lat = LAT_MAX - ((y + 0.5) / HEIGHT) * (LAT_MAX - LAT_MIN)
        bits.push(geoContains(land, [lon, lat]) ? 1 : 0)
    }
}

// Pack 8 samples per byte, most significant bit first.
const bytes = Buffer.alloc(Math.ceil(bits.length / 8))
bits.forEach((bit, index) => {
    if (bit) bytes[index >> 3] |= 0x80 >> (index & 7)
})

const filled = bits.reduce((total, bit) => total + bit, 0)

const out = `// Generated by scripts/generate-world-dots.mjs - do not edit by hand.
// Natural Earth land polygons (world-atlas, 110m) sampled on an equirectangular
// grid, packed 8 samples per byte. ${filled} of ${bits.length} cells are land.

export const WORLD_DOTS = {
    width: ${WIDTH},
    height: ${HEIGHT},
    latMax: ${LAT_MAX},
    latMin: ${LAT_MIN.toFixed(4)},
    /** Packed land bitmask, most significant bit first. */
    bits: '${bytes.toString('base64')}',
} as const

/** Expands the packed bitmask into one boolean per grid cell. */
export function decodeWorldDots(): boolean[] {
    const binary = typeof atob === 'function' ? atob(WORLD_DOTS.bits) : Buffer.from(WORLD_DOTS.bits, 'base64').toString('binary')
    const total = WORLD_DOTS.width * WORLD_DOTS.height
    const cells: boolean[] = new Array(total)

    for (let index = 0; index < total; index += 1) {
        const byte = binary.charCodeAt(index >> 3)
        cells[index] = (byte & (0x80 >> (index & 7))) !== 0
    }

    return cells
}

/** Longitude/latitude to a 0-1 position on the map, matching the sampling grid. */
export function project(lon: number, lat: number): { x: number; y: number } {
    return {
        x: (lon + 180) / 360,
        y: (WORLD_DOTS.latMax - lat) / (WORLD_DOTS.latMax - WORLD_DOTS.latMin),
    }
}
`

writeFileSync('src/components/Home/map/world-dots.ts', out)
console.log(`wrote ${filled}/${bits.length} land cells, ${bytes.length} bytes packed`)
